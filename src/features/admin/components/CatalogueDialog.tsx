"use client";

import { Dialog } from "@base-ui/react/dialog";
import { type ReactNode, useEffect, useMemo, useState } from "react";

import { buttonClass } from "@/features/admin/components/ui/Button";
import { jetBrainsMono } from "@/features/admin/components/ui/mono-font";
import { CATALOGUE_PATH } from "@/features/backgrounds/utils/paths";

const TOKEN = /("(?:[^"\\]|\\.)*")(\s*:)?|(-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?)|\b(true|false|null)\b|([{}[\],])/g;

/** Pretty-printed JSON with its keys, strings, numbers and literals coloured. */
const highlight = (json: string) => {
  const nodes: ReactNode[] = [];
  let last = 0;

  for (const match of json.matchAll(TOKEN)) {
    const [text, string, colon, number, literal] = match;
    const tone = string ? (colon ? "text-sky-400" : "text-log-added") : number ? "text-amber-300" : literal ? "text-log-fixed" : "text-[#7f8da0]";

    nodes.push(json.slice(last, match.index));
    nodes.push(
      <span key={match.index} className={tone}>
        {string && colon ? string : text}
      </span>
    );

    // A key's colon is punctuation, not part of the key
    if (string && colon) {
      nodes.push(<span key={`${match.index}:`} className="text-[#7f8da0]">{colon}</span>);
    }

    last = match.index + text.length;
  }

  nodes.push(json.slice(last));

  return nodes;
};

const LOADING_COPY = [
  "Crunching the catalogue…",
  "Counting every tulip and canal…",
  "Asking the photos to line up…",
  "Indenting with great care…",
  "Polishing the curly braces…",
];

const Loading = () => {
  const [line, setLine] = useState(0);

  useEffect(() => {
    const timer = setInterval(() => setLine((current) => (current + 1) % LOADING_COPY.length), 1600);

    return () => clearInterval(timer);
  }, []);

  return (
    <div role="status" className="flex h-full flex-col items-center justify-center gap-4 text-sm text-[#7f8da0]">
      <span aria-hidden="true" className="size-8 animate-spin rounded-full border-[3px] border-dark-pill border-t-sky-400" />
      <span key={line} className="animate-fade-in">
        {LOADING_COPY[line]}
      </span>
    </div>
  );
};

type Contents = { text: string } | { error: string };

/** Shows catalogue.json, read fresh every time it opens, in a modal. */
export const CatalogueDialog = ({ className }: { className?: string }) => {
  const [contents, setContents] = useState<Contents | null>(null);

  const body = useMemo(() => (contents && "text" in contents ? highlight(contents.text) : null), [contents]);

  const load = async () => {
    setContents(null);

    try {
      const response = await fetch(CATALOGUE_PATH, { cache: "no-store" });

      if (!response.ok) {
        throw new Error(`Couldn't load ${CATALOGUE_PATH} (${response.status}).`);
      }

      setContents({ text: JSON.stringify(await response.json(), null, 2) });
    } catch (error) {
      setContents({ error: error instanceof Error ? error.message : String(error) });
    }
  };

  return (
    <Dialog.Root onOpenChange={(open) => open && load()}>
      <Dialog.Trigger className={className}>catalogue.json</Dialog.Trigger>
      <Dialog.Portal>
        <Dialog.Backdrop className="fixed inset-0 z-50 bg-black/70 backdrop-blur-xs duration-150 data-ending-style:opacity-0 data-starting-style:opacity-0" />
        <Dialog.Popup className="fixed top-1/2 left-1/2 z-50 flex h-[85vh] w-[calc(100%-2rem)] max-w-3xl -translate-1/2 flex-col gap-3 rounded-2xl bg-[#1b2638] p-6 text-dark-text shadow-2xl ring-1 ring-[#33465f] duration-150 ring-inset data-ending-style:scale-95 data-ending-style:opacity-0 data-starting-style:scale-95 data-starting-style:opacity-0">
          <Dialog.Title className="text-lg font-bold">catalogue.json</Dialog.Title>
          <Dialog.Description className="text-sm text-[#7f8da0]">
            What the extension downloads, as generated by the last rebuild.
          </Dialog.Description>
          {/* A fixed height, so the modal doesn't jump when the contents arrive */}
          <div className="min-h-0 flex-1 overflow-auto rounded-lg bg-[#0b121c]">
            {contents === null ? (
              <Loading />
            ) : (
              <pre className={`${jetBrainsMono.className} p-3 text-xs leading-relaxed text-dark-text`}>
                {"error" in contents ? contents.error : body}
              </pre>
            )}
          </div>
          <div className="flex justify-end gap-2">
            <a href={CATALOGUE_PATH} target="_blank" rel="noopener noreferrer" className={buttonClass("ghost")}>
              Open raw
            </a>
            <Dialog.Close type="button" className={buttonClass("dark")}>
              Close
            </Dialog.Close>
          </div>
        </Dialog.Popup>
      </Dialog.Portal>
    </Dialog.Root>
  );
};
